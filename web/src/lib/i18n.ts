export type Dict = typeof en;
// Widen the en literal type so the uk dict (which has different string
// values for the same keys) still satisfies the record. Without `Record<keyof Dict, string>`
// TypeScript treats Dict as having literal types, which makes uk's strings
// "not assignable to type 'Catalog'" etc.
const dicts: Record<Locale, Record<keyof Dict, string>> = { en, uk };

function getInitialLocale(): Locale {
  if (typeof window === "undefined") return "en";
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "en" || stored === "uk") return stored;
  if (navigator.language?.toLowerCase().startsWith("uk")) return "uk";
  return "en";
}

export function applyLocale(l: Locale) {
  if (typeof document === "undefined") return;
  document.documentElement.setAttribute("lang", l);
}
export function bootstrapLocale() {
  applyLocale(getInitialLocale());
}

/** Read current locale (does not subscribe to changes — use `useI18n` for that). */
export function getLocale(): Locale {
  return getInitialLocale();
}

/**
 * Resolve a translation key. Supports simple `{name}` interpolation, e.g.
 * t("chat.empty.title.tour", { city: "Reykjavik" }).
 */
function format(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

// ---------------------------------------------------------------------------
//  React Context — one source of truth for the whole app.
//
//  Earlier each call to useI18n() got its OWN useState, so a click on the
//  LangSwitcher only re-rendered the switcher itself; other components
//  still showed their initial render. The Provider below shares one state.
// ---------------------------------------------------------------------------

interface I18nValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: keyof Dict, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);

  useEffect(() => {
    // Sync if another tab changes the language
    const onStorage = (e: StorageEvent) => {
      if (e.key === STORAGE_KEY && (e.newValue === "en" || e.newValue === "uk")) {
        setLocaleState(e.newValue);
        applyLocale(e.newValue);
      }
    };
    window.addEventListener("storage", onStorage);
    return () => window.removeEventListener("storage", onStorage);
  }, []);

  function setLocale(l: Locale) {
    setLocaleState(l);
    applyLocale(l);
    localStorage.setItem(STORAGE_KEY, l);
  }

  function t(key: keyof Dict, vars?: Record<string, string | number>): string {
    const dict = dicts[locale] || en;
    return format(dict[key] ?? en[key] ?? String(key), vars);
  }

  return createElement(I18nContext.Provider, { value: { locale, setLocale, t } }, children);
}

/**
 * Soft-translate a backend-provided string (theme id, meal-plan name,
 * country name). Looks up the key in the current dictionary; if missing,
 * returns the original string unchanged — so a tour with an unknown theme
 * still renders cleanly. Used in TourCard, ThemeTile, etc.
 */
export function softT(
  t: (k: keyof Dict, vars?: Record<string, string | number>) => string,
  prefix: string,
  value: string
): string {
  const key = `${prefix}.${value}` as keyof Dict;
  const translated = t(key);
  // If the key wasn't in the dictionary, t() returns the key itself —
  // detect that case and return the original value instead.
  return translated === String(key) ? value : translated;
}


export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (ctx) return ctx;
  // Fallback for early/test renders without provider — uses initial locale,
  // setter is a no-op. Never reached in normal flow because <I18nProvider>
  // wraps the whole app in main.tsx.
  const locale = getInitialLocale();
  return {
    locale,
    setLocale: () => { /* no provider */ },
    t: (key, vars) => format((dicts[locale] || en)[key] ?? en[key] ?? String(key), vars),
  };
}
